  - 结丹→元婴：搜集珍稀材料炼制元婴丹药，或寻找古修遗迹获取突破机缘，最终需要渡天劫。天劫九死一生。
  - 元婴→化神：需要感悟天地法则，寻找上古传承或天道碎片，最终渡化神天劫。化神天劫威力恐怖，需要充分准备。
