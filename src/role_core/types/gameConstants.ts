// ═══════════════════════════════════════════════════════════════════════════

export interface GradeConstraint {
  /** 品阶上限；缺省表示不限。 */
  max?: ItemGrade;
  /** 品阶下限；缺省表示不限。 */
  min?: ItemGrade;
  /**
   * 指定品阶（AI / 剧情明确给出的品阶），存在时直接采用、跳过随机。
   * 用于让「花十灵石买的便宜货」稳定是下品，而不是随机摇出神品。
   */
  pinned?: ItemGrade;
}

